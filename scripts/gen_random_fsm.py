#!/usr/bin/env python3
"""Generate a random Mealy FSM (fsm.v) and assertion set (assertions.sva).

The FSM style follows the contest example: a case on the present state, each
state holding a casex on the packed input with x-heavy patterns and a default.
Each state has a base output vector and every transition flips a few bits of
it, so outputs rise and fall often enough to make the assertions interesting.

Example (the dimensions of public case 1):
    python3 scripts/gen_random_fsm.py --states 36 --inputs 7 --outputs 7 \
        --assertions 10 --seed 1 -o benchmarks/rand_m
"""
import argparse
import os
import random


def bits(rng, width, p_one=0.5):
    return "".join("1" if rng.random() < p_one else "0" for _ in range(width))


def pattern(rng, width, p_x=0.6):
    return "".join("x" if rng.random() < p_x else rng.choice("01") for _ in range(width))


def flip(rng, vec, p_flip):
    return "".join(("1" if c == "0" else "0") if rng.random() < p_flip else c for c in vec)


def write_fsm(path, rng, n_states, n_in, n_out):
    sw = max(1, (n_states - 1).bit_length())
    base = [bits(rng, n_out) for _ in range(n_states)]
    lines = [
        "// Randomly generated by scripts/gen_random_fsm.py",
        "module fsm(clk, rst, in, out);",
        "input clk, rst;",
        f"input [{n_in - 1}:0] in;",
        f"output [{n_out - 1}:0] out;",
        "",
    ]
    params = [f"S{i} = {sw}'d{i}" for i in range(n_states)]
    lines.append("parameter " + ",\n          ".join(params) + ";")
    lines += [
        f"reg [{sw - 1}:0] pstate, nstate;",
        f"reg [{n_out - 1}:0] out;",
        "",
        "always @(posedge clk or posedge rst) begin",
        "    if (rst) pstate <= S0;",
        "    else pstate <= nstate;",
        "end",
        "",
        "always @(*) begin",
        "    nstate = pstate;",
        f"    out = {n_out}'d0;",
        "    case (pstate)",
    ]
    for s in range(n_states):
        lines.append(f"        S{s}: casex (in)")
        for _ in range(rng.randint(1, 3)):
            nxt = rng.randrange(n_states)
            out = flip(rng, base[nxt], 0.15)
            lines.append(f"            {n_in}'b{pattern(rng, n_in)}: begin nstate = S{nxt}; "
                         f"out = {n_out}'b{out}; end")
        # The default keeps the states chained so that all of them are reachable.
        nxt = (s + 1) % n_states
        out = flip(rng, base[nxt], 0.15)
        lines.append(f"            default: begin nstate = S{nxt}; out = {n_out}'b{out}; end")
        lines.append("        endcase")
    lines += ["    endcase", "end", "", "endmodule", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))


def write_assertions(path, rng, n_in, n_out, n_rules):
    out = ["// Randomly generated by scripts/gen_random_fsm.py"]
    i = 0
    while i < n_rules:
        if rng.random() < 0.5:
            trig = f"{rng.choice(['$rose', '$fell'])}(in[{rng.randrange(n_in)}])"
        else:
            trig = f"{rng.choice(['$rose', '$fell'])}(out[{rng.randrange(n_out)}])"
        fn = rng.choices(["$rose", "$fell", "$stable"], weights=[45, 45, 10])[0]
        cons = f"{fn}(out[{rng.randrange(n_out)}])"
        a = rng.randint(0, 3)
        b = a + rng.randint(0, 5)
        windows = [(a, b)]
        # Sometimes add a dominated twin: same conditions, narrower window.
        if b > a and i + 1 < n_rules and rng.random() < 0.2:
            windows.append((a + 1, b))
        for lo, hi in windows:
            i += 1
            out.append(f"r{i}: assert property (@(posedge clk) {trig} |-> ##[{lo}:{hi}] {cons});")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--states", type=int, required=True)
    ap.add_argument("--inputs", type=int, required=True)
    ap.add_argument("--outputs", type=int, required=True)
    ap.add_argument("--assertions", type=int, required=True)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("-o", "--out-dir", required=True)
    args = ap.parse_args()

    rng = random.Random(args.seed)
    os.makedirs(args.out_dir, exist_ok=True)
    write_fsm(os.path.join(args.out_dir, "fsm.v"), rng, args.states, args.inputs, args.outputs)
    write_assertions(os.path.join(args.out_dir, "assertions.sva"), rng, args.inputs, args.outputs,
                     args.assertions)


if __name__ == "__main__":
    main()
